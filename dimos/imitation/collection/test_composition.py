@pytest.mark.parametrize(
    ("source", "stream", "kind"),
    [
        ("measured_positions", "coordinator_joint_state", "snapshot"),
        ("accepted_targets", "applied_joint_position_command", "joint_position_updates"),
    ],
)
def test_generated_contract_preserves_joint_order_and_action_meaning(
    source, stream, kind, tmp_path
):
    profile = joint_rgb_profile(
        name="demo",
        robot_type="test",
        joints=["arm/gripper", "arm/joint1"],
        cameras={"wrist": WebcamConfig(width=320, height=240, fps=20)},
        action_source=source,
    )
    schema = profile.to_schema()
    (tmp_path / "schema.json").write_text(schema.model_dump_json())
    (tmp_path / schema.payload).touch()
    saved = RecordingSchema.read(tmp_path)

    assert saved.action["action"].names == ["arm/gripper", "arm/joint1"]
    assert saved.action["action"].shape == (2,)
    assert saved.action["action"].stream == stream
    assert saved.action["action"].source_kind == kind
    assert saved.observation["observation.state"].source_kind == "snapshot"
    assert saved.observation["observation.images.wrist"].shape == (240, 320, 3)
    assert saved.sync.anchor == "observation.images.wrist"
    assert saved.sync.rate_hz == 20
    assert saved.sync.tolerance_ms == 20
    expected = {"wrist_image": Image, "coordinator_joint_state": JointState}
    if source == "accepted_targets":
        expected["applied_joint_position_command"] = JointState
    assert profile.input_types() == expected


def test_collect_wires_each_camera_once_and_preserves_control_graph():
    hardware = HardwareComponent("test", HardwareType.WHOLE_BODY, joints=["a", "b"])
    control = ControlCoordinator.blueprint(instance_name="ControlCoordinator", hardware=[hardware])
    cameras = {
        "left_wrist": WebcamConfig(fps=30),
        "right_wrist": WebcamConfig(camera_index=1, fps=30),
    }
    graph = collect(
        name="dual-test",
        cameras=cameras,
        control=control,
        action_source="accepted_targets",
    )
    # The result remains an ordinary composable Blueprint.
    atoms = autoconnect(graph).active_blueprints
    assert sum(atom.module is ControlCoordinator for atom in atoms) == 1
    recorder = next(atom for atom in atoms if atom.name == "recorder")
    monitor = next(atom for atom in atoms if atom.module is EpisodeMonitorModule)
    assert monitor.kwargs == {"instance_name": "episodes"}
    assert {s.name for s in recorder.streams if s.direction == "in"} >= {
        "left_wrist_image",
        "right_wrist_image",
        "coordinator_joint_state",
        "applied_joint_position_command",
        "status",
    }
    assert {
        a.name: a.kwargs["hardware"].camera_index for a in atoms if a.module is CameraModule
    } == {
        "left_wrist": 0,
        "right_wrist": 1,
    }
    assert graph.remapping_map[("left_wrist", "color_image")] == "left_wrist_image"
    assert graph.remapping_map[("right_wrist", "color_image")] == "right_wrist_image"
    assert recorder.kwargs["recording_schema"].robot_type == "test"
    assert set(recorder.kwargs["recording_schema"].observation) == {
        "observation.images.left_wrist",
        "observation.images.right_wrist",
        "observation.state",
    }
    assert cameras["left_wrist"].frame_id_prefix is None


