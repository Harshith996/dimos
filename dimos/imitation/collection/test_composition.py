def test_custom_sync_and_extra_sensor_survive_the_saved_contract():
    velocity = FeatureSpec(
        stream="coordinator_joint_state",
        message_type=JointState,
        field="velocity",
        dtype="float32",
        shape=(1,),
        names=["arm/joint1"],
    )
    profile = joint_rgb_profile(
        name="custom",
        robot_type="arm",
        joints=["arm/joint1"],
        cameras={"wrist": WebcamConfig(fps=30)},
        action_source="measured_positions",
        sync=SyncConfig(anchor="observation.state", rate_hz=10, tolerance_ms=50),
        extra_observations={"observation.velocity": velocity},
    )
    saved = profile.to_schema()
    assert (
        saved.sync.model_dump()
        == SyncConfig(
            anchor="observation.state",
            rate_hz=10,
            tolerance_ms=50,
        ).model_dump()
    )
    assert saved.observation["observation.velocity"].field == "velocity"
    assert profile.input_types() == {"wrist_image": Image, "coordinator_joint_state": JointState}


def test_extra_sensor_cannot_silently_replace_standard_state():
    with pytest.raises(ValueError, match="replaces a standard feature"):
        joint_rgb_profile(
            name="custom",
            robot_type="arm",
            joints=["a"],
            cameras={"wrist": WebcamConfig()},
            action_source="measured_positions",
            extra_observations={
                "observation.state": FeatureSpec(
                    names=["a"],
                    stream="other",
                    message_type=JointState,
                    field="position",
                    dtype="float32",
                    shape=(1,),
                )
            },
        )


